test("Wide video uses a 16:9 wrapper and gains a wide display only in show-all Horizontal; square size honors available height", async ({ page }) => {
  const root = gallery(page)
  await thumbnails(root).nth(3).click()
  await expect(main(root)).toHaveAttribute("data-square", "true")
  const ratio = () => main(root).locator(".fiori-media-gallery-item__wrapper").evaluate((element) => element.getBoundingClientRect().height / element.getBoundingClientRect().width)
  await expect.poll(ratio).toBeCloseTo(9 / 16, 2)
  await expect(main(root).locator("video")).toBeVisible()
  await page.locator("#media-gallery-demo #media-gallery-show-all").click()
  await expect(main(root)).not.toHaveAttribute("data-square", "true")
  await expect.poll(ratio).toBeCloseTo(9 / 16, 2)
  await page.locator("#media-gallery-demo #media-gallery-layout").click()
  await page.locator("#media-gallery-demo #media-gallery-layout").click()
  await expect(root).toHaveAttribute("data-effective-layout", "Vertical")
  await expect(main(root)).toHaveAttribute("data-square", "true")
  await expect.poll(() => main(root).evaluate((element) => (element as HTMLElement).offsetWidth)).toBe(288)
})

