import { expect, test, type Locator } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.goto("/index.html")
  await page.waitForSelector("html[data-ready=true]")
})
const gallery = (page: { locator: (selector: string) => Locator }) => page.locator("#media-gallery-demo #media-gallery-basic")
const thumbnails = (root: Locator) => root.locator(".fiori-media-gallery__thumbnail")
const focusItems = (root: Locator) => thumbnails(root).locator(".fiori-media-gallery-item__root")
const main = (root: Locator) => root.locator(".fiori-media-gallery__display > [data-slot=media-gallery-item]")

test("media gallery selects by click, ignores disabled and duplicate selections, and suppresses the initial callback", async ({ page }) => {
  const root = gallery(page)
  await expect(root.getByRole("listbox", { name: "Product pictures" })).toBeVisible()
  await expect(thumbnails(root)).toHaveCount(4)
  await expect(thumbnails(root).nth(0)).toHaveAttribute("aria-checked", "true")
  await expect(page.locator("#media-gallery-demo #media-gallery-selection")).toHaveText("Selection: none; changes: 0")
  await thumbnails(root).nth(1).click()
  await expect(thumbnails(root).nth(0)).toHaveAttribute("aria-checked", "true")
  await thumbnails(root).nth(2).click()
  await expect(thumbnails(root).nth(2)).toHaveAttribute("aria-checked", "true")
  await expect(main(root).getByAltText("Product picture 2")).toBeVisible()
  await expect(page.locator("#media-gallery-demo #media-gallery-selection")).toHaveText("Selection: media-gallery-item-2:true; changes: 1")
  await thumbnails(root).nth(2).click()
  await expect(page.locator("#media-gallery-demo #media-gallery-selection")).toHaveText("Selection: media-gallery-item-2:true; changes: 1")
})

test("thumbnail keyboard navigation moves focus without selection, skips disabled, and activates Enter-down and Space-up", async ({ page }) => {
  const root = gallery(page), items = focusItems(root)
  await items.nth(0).focus()
  await page.keyboard.press("ArrowRight")
  await expect(items.nth(2)).toBeFocused()
  await expect(thumbnails(root).nth(0)).toHaveAttribute("aria-checked", "true")
  await page.keyboard.down("Enter")
  await expect(thumbnails(root).nth(2)).toHaveAttribute("aria-checked", "true")
  await page.keyboard.up("Enter")
  await page.keyboard.press("ArrowDown")
  await expect(items.nth(3)).toBeFocused()
  await page.keyboard.down("Space")
  await expect(thumbnails(root).nth(2)).toHaveAttribute("aria-checked", "true")
  await page.keyboard.up("Space")
  await expect(thumbnails(root).nth(3)).toHaveAttribute("aria-checked", "true")
  await expect(page.locator("#media-gallery-demo #media-gallery-selection")).toHaveText("Selection: media-gallery-item-3:true; changes: 2")
})

test("static navigation includes overflow, all arrow axes, Home/End, PageUp/PageDown and excludes modifier combinations", async ({ page }) => {
  const root = gallery(page), items = focusItems(root), overflow = root.locator(".fiori-media-gallery__overflow button")
  await items.nth(0).focus()
  await page.keyboard.press("ArrowLeft")
  await expect(items.nth(0)).toBeFocused()
  await page.keyboard.press("End")
  await expect(overflow).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(overflow).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(page.locator("#media-gallery-demo #media-gallery-events")).toHaveText("Overflow: 1; display: 0")
  await page.keyboard.press("PageUp")
  await expect(items.nth(0)).toBeFocused()
  await page.keyboard.press("Control+ArrowRight")
  await expect(items.nth(0)).toBeFocused()
  await page.keyboard.press("PageDown")
  await expect(overflow).toBeFocused()
  await page.keyboard.press("ArrowUp")
  await expect(items.nth(3)).toBeFocused()
  await page.keyboard.press("ArrowLeft")
  await expect(items.nth(2)).toBeFocused()
  await page.keyboard.press("Home")
  await expect(items.nth(0)).toBeFocused()
})

test("RTL reverses left/right navigation while vertical navigation stays the same", async ({ page }) => {
  const root = gallery(page), items = focusItems(root)
  await root.evaluate((element) => { element.setAttribute("dir", "rtl") })
  await items.nth(0).focus()
  await page.keyboard.press("ArrowLeft")
  await expect(items.nth(2)).toBeFocused()
  await page.keyboard.press("ArrowRight")
  await expect(items.nth(0)).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(items.nth(2)).toBeFocused()
})

test("display click is emitted only when interactive; the display receives a keyboard tab stop without selecting a thumbnail", async ({ page }) => {
  const root = gallery(page), display = main(root).locator(".fiori-media-gallery-item__root")
  await expect(display).toHaveAttribute("tabindex", "0")
  await display.click()
  await expect(page.locator("#media-gallery-demo #media-gallery-events")).toHaveText("Overflow: 0; display: 1")
  await page.locator("#media-gallery-demo #media-gallery-interactive").click()
  await expect(display).not.toHaveAttribute("tabindex", "0")
  await display.click()
  await expect(page.locator("#media-gallery-demo #media-gallery-events")).toHaveText("Overflow: 0; display: 1")
})

test("Auto follows actual component width at 599/600 and uses the desktop thumbnail path even in a narrow viewport", async ({ page }) => {
  const root = gallery(page)
  await page.setViewportSize({ width: 500, height: 900 })
  await root.evaluate((element) => { (element as HTMLElement).style.width = "599px" })
  await expect(root).toHaveAttribute("data-effective-layout", "Vertical")
  await expect(root).toHaveAttribute("data-media-range", "S")
  await expect(root.locator(".fiori-carousel")).toHaveCount(0)
  await expect(root.getByRole("listbox")).toBeVisible()
  await root.evaluate((element) => { (element as HTMLElement).style.width = "600px" })
  await expect(root).toHaveAttribute("data-effective-layout", "Horizontal")
  await expect(root).toHaveAttribute("data-media-range", "M")
})

test("overflow measures actual height and width, reserves a button, counts disabled items, and caps capacity at five", async ({ page }) => {
  const root = gallery(page), overflow = root.locator(".fiori-media-gallery__overflow button")
  await expect(overflow).toHaveText("+3")
  await root.evaluate((element) => { (element as HTMLElement).style.height = "336px" })
  await expect(thumbnails(root)).toHaveCount(3)
  await expect(overflow).toHaveText("+4")
  await root.evaluate((element) => { (element as HTMLElement).style.height = "80px" })
  await expect(thumbnails(root)).toHaveCount(0)
  await expect(overflow).toHaveText("+7")
  await root.evaluate((element) => { (element as HTMLElement).style.height = "800px" })
  await expect(thumbnails(root)).toHaveCount(4)
  await expect(overflow).toHaveText("+3")
  await page.locator("#media-gallery-demo #media-gallery-layout").click()
  await expect(root).toHaveAttribute("data-effective-layout", "Horizontal")
  await page.locator("#media-gallery-demo #media-gallery-layout").click()
  await expect(root).toHaveAttribute("data-effective-layout", "Vertical")
  await root.evaluate((element) => { (element as HTMLElement).style.width = "352px" })
  await expect(thumbnails(root)).toHaveCount(3)
  await expect(overflow).toHaveText("+4")
})

test("show-all removes overflow, scrolls thumbnails, and uses 1/2/3/4 columns at the native ranges", async ({ page }) => {
  const root = gallery(page), list = root.getByRole("listbox")
  await page.locator("#media-gallery-demo #media-gallery-show-all").click()
  await page.locator("#media-gallery-demo #media-gallery-layout").click()
  await expect(thumbnails(root)).toHaveCount(7)
  await expect(root.locator(".fiori-media-gallery__overflow")).toHaveCount(0)
  for (const [width, range, listWidth] of [[599, "S", 80], [600, "M", 160], [1024, "L", 240], [1440, "XL", 320]] as const) {
    await root.evaluate((element, next) => { (element as HTMLElement).style.width = next + "px" }, width)
    await expect(root).toHaveAttribute("data-media-range", range)
    await expect.poll(() => list.evaluate((element) => (element as HTMLElement).offsetWidth)).toBe(listWidth)
  }
  expect(await root.locator(".fiori-media-gallery__thumbnails-wrapper").evaluate((element) => getComputedStyle(element).overflowY)).toBe("auto")
})

test("Wide video uses a 16:9 wrapper and gains a wide display only in show-all Horizontal; square size honors available height", async ({ page }) => {
  const root = gallery(page)
  await thumbnails(root).nth(3).click()
  await expect(main(root)).toHaveAttribute("data-square", "true")
  const ratio = () => main(root).locator(".fiori-media-gallery-item__wrapper").evaluate((element) => element.getBoundingClientRect().height / element.getBoundingClientRect().width)
  await expect.poll(ratio).toBeCloseTo(9 / 16, 2)
  await expect(main(root).locator("video")).toBeVisible()
  await page.locator("#media-gallery-demo #media-gallery-show-all").click()
  await expect(main(root)).not.toHaveAttribute("data-square", "true")
  await expect.poll(ratio).toBeCloseTo(9 / 16, 2)
  await page.locator("#media-gallery-demo #media-gallery-layout").click()
  await page.locator("#media-gallery-demo #media-gallery-layout").click()
  await expect(root).toHaveAttribute("data-effective-layout", "Vertical")
  await expect(main(root)).toHaveAttribute("data-square", "true")
  await expect.poll(() => main(root).evaluate((element) => (element as HTMLElement).offsetWidth)).toBe(288)
})

test("invalid first selected falls back to first selectable; hidden focus consumes its native slot and becomes a no-op", async ({ page }) => {
  const invalid = page.locator("#media-gallery-demo #media-gallery-invalid")
  await expect(thumbnails(invalid).nth(0)).toHaveAttribute("aria-checked", "true")
  await expect(thumbnails(invalid).nth(3)).toHaveAttribute("aria-checked", "false")
  const root = page.locator("#media-gallery-demo #media-gallery-hidden"), items = focusItems(root)
  await items.nth(0).focus()
  await page.keyboard.press("ArrowDown")
  await expect(items.nth(1)).toHaveAttribute("tabindex", "0")
  await expect(items.nth(0)).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(items.nth(0)).toBeFocused()
  await expect(items.nth(2)).toHaveAttribute("tabindex", "-1")
})

test("programmatic overflow selection does not fire; removing every item clears the display, and all-disabled initial items have no content", async ({ page }) => {
  const root = gallery(page)
  await page.locator("#media-gallery-demo #media-gallery-select-last").click()
  await expect(main(root).getByAltText("Product picture 6")).toBeVisible()
  await expect(page.locator("#media-gallery-demo #media-gallery-selection")).toHaveText("Selection: none; changes: 0")
  await page.locator("#media-gallery-demo #media-gallery-clear").click()
  await expect(main(root).locator("img,video")).toHaveCount(0)
  await expect(thumbnails(root)).toHaveCount(0)
  const disabled = page.locator("#media-gallery-demo #media-gallery-disabled")
  await expect(main(disabled).locator("img,video")).toHaveCount(0)
})

test("mouse selection has no focus ring and keyboard focus has the native ring", async ({ page }) => {
  const root = gallery(page), items = focusItems(root)
  await items.nth(0).click()
  await expect(items.nth(0)).toBeFocused()
  expect(await items.nth(0).evaluate((element) => getComputedStyle(element).outlineStyle)).toBe("none")
  await page.keyboard.press("ArrowDown")
  await expect(items.nth(2)).toBeFocused()
  expect(await items.nth(2).evaluate((element) => getComputedStyle(element).outlineStyle)).not.toBe("none")
})

test.describe("native phone platform", () => {
  test.use({
    hasTouch: true, isMobile: true, viewport: { width: 390, height: 844 }, deviceScaleFactor: 2,
    userAgent: "Mozilla/5.0 (Linux; Android 11; Pixel 5) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Mobile Safari/537.36",
  })
  test("phone reuses Carousel, hides thumbnails and disabled items, and reports navigation without changing gallery selected flags", async ({ page }) => {
    const root = gallery(page), items = root.locator(".fiori-carousel__item")
    await expect(root).toHaveAttribute("data-phone", "true")
    await expect(root.getByRole("listbox")).toHaveCount(0)
    await expect(items).toHaveCount(6)
    await expect(root.locator("[data-carousel-arrow]")).toHaveCount(0)
    await expect(root.locator("#media-gallery-item-0")).toHaveAttribute("data-selected", "true")
    await items.nth(0).focus()
    await page.keyboard.press("ArrowRight")
    await expect(items.nth(1)).toBeFocused()
    await expect(root.locator("#media-gallery-item-2")).not.toHaveAttribute("data-selected", "true")
    await expect(root.locator("#media-gallery-item-0")).toHaveAttribute("data-selected", "true")
    await expect(page.locator("#media-gallery-demo #media-gallery-selection")).toHaveText("Selection: media-gallery-item-2:false; changes: 1")
    await page.locator("#media-gallery-demo #media-gallery-select-last").click()
    await expect(root.locator("#media-gallery-item-6")).toHaveAttribute("data-selected", "true")
    await expect(items.nth(5)).toHaveAttribute("aria-hidden", "false")
    await expect(page.locator("#media-gallery-demo #media-gallery-selection")).toHaveText("Selection: media-gallery-item-2:false; changes: 1")
  })
})
