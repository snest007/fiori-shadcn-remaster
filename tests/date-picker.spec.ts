import { expect, test, type Page } from "@playwright/test"

// The open picker popover (only one is open at a time).
const popover = (page: Page) => page.locator("[data-slot=picker-popover]")

test.describe("DatePicker (Fiori model)", () => {
  test.beforeEach(async ({ page }) => {
    await page.goto("/index.html#/date-picker")
    await page.waitForSelector("html[data-ready=true]")
  })

  test("ARIA and F4 / Alt+Down open the calendar with the value's day focused; Escape closes", async ({ page }) => {
    const input = page.locator("#date-picker-main")
    await expect(input).toHaveAttribute("aria-roledescription", "Date Input")
    await expect(input).toHaveAttribute("aria-haspopup", "grid")
    await input.focus()
    await page.keyboard.press("F4")
    await expect(popover(page)).toBeVisible()
    const focused = popover(page).locator('[role=gridcell][tabindex="0"]')
    await expect(focused).toBeFocused()
    await expect(focused).toHaveAttribute("data-date", "20240312")
    await expect(focused).toHaveAttribute("aria-selected", "true")
    await page.keyboard.press("Escape")
    await expect(popover(page)).toHaveCount(0)
    await expect(input).toBeFocused()
    await page.keyboard.press("Alt+ArrowDown")
    await expect(popover(page)).toBeVisible()
    await page.keyboard.press("Alt+ArrowUp")
    await expect(popover(page)).toHaveCount(0)
  })

  test("picking a day commits it and closes", async ({ page }) => {
    const input = page.locator("#date-picker-main")
    await input.focus()
    await page.keyboard.press("F4")
    await page.keyboard.press("ArrowRight")
    await page.keyboard.press("Enter")
    await expect(popover(page)).toHaveCount(0)
    await expect(input).toHaveValue("Mar 13, 2024")
    await expect(page.getByTestId("date-picker-value")).toHaveText("Mar 13, 2024")
    await expect(input).toBeFocused()
    await page.locator("#date-picker-main ~ * [data-slot=picker-field-icon]").click()
    await expect(popover(page)).toBeVisible()
    await popover(page).locator('[data-date="20240320"]').click()
    await expect(input).toHaveValue("Mar 20, 2024")
  })

  test("PageUp/PageDown change the day, Shift the month, Ctrl+Shift the year", async ({ page }) => {
    const input = page.locator("#date-picker-main")
    await input.focus()
    await page.keyboard.press("PageUp")
    await expect(input).toHaveValue("Mar 13, 2024")
    await page.keyboard.press("PageDown")
    await page.keyboard.press("PageDown")
    await expect(input).toHaveValue("Mar 11, 2024")
    await page.keyboard.press("Shift+PageUp")
    await expect(input).toHaveValue("Apr 11, 2024")
    await page.keyboard.press("Control+Shift+PageDown")
    await expect(input).toHaveValue("Apr 11, 2023")
    await expect(page.getByTestId("date-picker-value")).toHaveText("Apr 11, 2023")
  })

  test("typed text is parsed leniently and normalized; invalid text is negative", async ({ page }) => {
    const input = page.locator("#date-picker-main")
    const field = page.locator("#date-picker-demo [data-slot=picker-field]").first()
    await input.fill("3/5/24")
    await page.keyboard.press("Enter")
    await expect(input).toHaveValue("Mar 5, 2024")
    await expect(page.getByTestId("date-picker-date")).toHaveText(new Date(2024, 2, 5).toDateString())
    await input.fill("2024-12-24")
    await page.keyboard.press("Enter")
    await expect(input).toHaveValue("Dec 24, 2024")
    await input.fill("Feb 30, 2024")
    await page.keyboard.press("Enter")
    await expect(field).toHaveAttribute("data-value-state", "negative")
    await expect(input).toHaveAttribute("aria-invalid", "true")
    await expect(page.getByTestId("date-picker-date")).toHaveText("—")
    await input.fill("Feb 3, 2024")
    await page.keyboard.press("Tab")
    await expect(field).not.toHaveAttribute("data-value-state")
    await expect(input).toHaveValue("Feb 3, 2024")
  })

  test("min/max: out-of-range days are disabled and out-of-range text is negative", async ({ page }) => {
    const input = page.locator("#date-picker-min-max")
    await input.focus()
    await page.keyboard.press("F4")
    await expect(popover(page).locator('[data-date="20240229"]')).toHaveAttribute("aria-disabled", "true")
    await expect(popover(page).locator("[data-slot=calendar-previous]")).toHaveAttribute("aria-disabled", "true")
    await page.keyboard.press("Escape")
    await input.fill("Apr 2, 2024")
    await page.keyboard.press("Enter")
    await expect(page.locator("#date-picker-demo [data-slot=picker-field]").nth(2)).toHaveAttribute("data-value-state", "negative")
  })

  test("locale and pattern: German dd.MM.yyyy, Monday first", async ({ page }) => {
    const input = page.locator("#date-picker-de")
    await input.focus()
    await page.keyboard.press("F4")
    await expect(popover(page).getByRole("columnheader").nth(1)).toHaveAttribute("aria-label", "Montag")
    await expect(popover(page).locator("[data-slot=calendar-month-button]")).toHaveText("März")
    await page.keyboard.press("ArrowRight")
    await page.keyboard.press("Enter")
    await expect(input).toHaveValue("13.03.2024")
  })

  test("a month pattern picks months", async ({ page }) => {
    const input = page.locator("#date-picker-month")
    await input.focus()
    await page.keyboard.press("F4")
    await expect(popover(page).locator('[data-picker="month"]')).toBeVisible()
    await page.keyboard.press("ArrowRight")
    await page.keyboard.press("Enter")
    await expect(input).toHaveValue("April 2024")
  })
})

test.describe("DateRangePicker", () => {
  test.beforeEach(async ({ page }) => {
    await page.goto("/index.html#/date-range-picker")
    await page.waitForSelector("html[data-ready=true]")
  })

  test("two days make a range; typed ranges are ordered", async ({ page }) => {
    const input = page.locator("#date-range-picker-main")
    await input.fill("Mar 14, 2024 - Mar 5, 2024")
    await page.keyboard.press("Enter")
    await expect(input).toHaveValue("Mar 5, 2024 - Mar 14, 2024")
    await page.keyboard.press("F4")
    await expect(popover(page).locator(".fiori-dp-item--selected-between")).toHaveCount(8)
    await popover(page).locator('[data-date="20240318"]').click()
    await expect(popover(page)).toBeVisible()
    await popover(page).locator('[data-date="20240320"]').click()
    await expect(popover(page)).toHaveCount(0)
    await expect(input).toHaveValue("Mar 18, 2024 - Mar 20, 2024")
    await expect(page.getByTestId("date-range-picker-value")).toHaveText("Mar 18, 2024 - Mar 20, 2024")
  })

  test("PageUp changes the date the caret is in", async ({ page }) => {
    const input = page.locator("#date-range-picker-main")
    await input.fill("Mar 5, 2024 - Mar 14, 2024")
    await page.keyboard.press("Enter")
    // Enter commits and re-formats the value; wait for that render before placing the caret, or it resets.
    await expect(page.getByTestId("date-range-picker-value")).toHaveText("Mar 5, 2024 - Mar 14, 2024")
    // Caret in the start date (macOS's Home key doesn't move the caret, so set it directly).
    await input.evaluate((el: HTMLInputElement) => el.setSelectionRange(0, 0))
    await page.keyboard.press("PageUp")
    await expect(input).toHaveValue("Mar 6, 2024 - Mar 14, 2024")
    await input.evaluate((el: HTMLInputElement) => el.setSelectionRange(el.value.length, el.value.length))
    await page.keyboard.press("PageDown")
    await expect(input).toHaveValue("Mar 6, 2024 - Mar 13, 2024")
  })
})
