test("adapt-filters-dialog: Cancel and Escape discard both values and visibility", async ({ page }) => {
  let dialog = await openDialog(page)
  await row(dialog, "name").getByRole("textbox", { name: "Name", exact: true }).fill("Changed")
  await row(dialog, "category").getByRole("button", { name: /Remove Filter/ }).click()
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  expect((await result(page)).visibleKeys).toEqual(["name", "category", "supplier"])
  expect((await result(page)).values.name[0].values).toEqual(["Notebook"])
  dialog = await openDialog(page)
  await expect(row(dialog, "name").getByRole("textbox", { name: "Name", exact: true })).toHaveValue("Notebook")
  await expect(row(dialog, "category")).toBeVisible()
  await row(dialog, "name").getByRole("textbox", { name: "Name", exact: true }).fill("Discarded")
  await page.keyboard.press("Escape")
  await expect(dialog).toHaveCount(0)
  await expect(page.locator("#adapt-filters-dialog-demo-open")).toBeFocused()
  expect((await result(page)).values.name[0].values).toEqual(["Notebook"])
})

test("adapt-filters-dialog: Reset asks for confirmation and restores the initial view", async ({ page }) => {
  const dialog = await openDialog(page)
  await row(dialog, "name").getByRole("textbox", { name: "Name", exact: true }).fill("Changed")
  await row(dialog, "category").getByRole("button", { name: /Remove Filter/ }).click()
  await dialog.getByRole("button", { name: "Reset", exact: true }).click()
  const warning = page.getByRole("alertdialog", { name: "Warning", exact: true })
  await expect(warning).toBeVisible()
  await expect(warning).toContainText("You are about to reset all the changes you made")
  await expect(warning).toContainText("to your filters and revert back to the selected view.")
  await warning.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(warning).toHaveCount(0)
  await expect(row(dialog, "name").getByRole("textbox", { name: "Name", exact: true })).toHaveValue("Changed")
  await dialog.getByRole("button", { name: "Reset", exact: true }).click()
  await expect(warning).toBeVisible()
  // The dialog shortcut must confirm this warning without applying the outer draft.
  await warning.getByRole("button", { name: "OK", exact: true }).press("Control+Enter")
  await expect(warning).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await expect(page.locator("#adapt-filters-dialog-demo-applies")).toHaveText("Applied 0 times")
  await expect(row(dialog, "name").getByRole("textbox", { name: "Name", exact: true })).toHaveValue("Notebook")
  await expect(row(dialog, "category")).toBeVisible()
  await expect(dialog.getByRole("button", { name: "Reset", exact: true })).toBeDisabled()
  await expect(dialog.locator('[role="status"][aria-live="assertive"]')).toHaveText("Filters have been reset to the initially selected view.")
  await dialog.getByRole("button", { name: "OK", exact: true }).click()
  expect((await result(page)).visibleKeys).toEqual(["name", "category", "supplier"])
})

