import { expect, test, type Locator, type Page } from "@playwright/test"

const dialogId = "#adapt-filters-dialog-demo-dialog"
const rowSelector = "[data-slot=adapt-filters-row]"

async function openDialog(page: Page) {
  await page.locator("#adapt-filters-dialog-demo-open").click()
  const dialog = page.locator(dialogId)
  await expect(dialog).toBeVisible()
  await expect(dialog).toHaveAccessibleName("Adapt Filters")
  return dialog
}

function row(dialog: Locator, key: string) {
  return dialog.locator(`${rowSelector}[data-key=${key}]`)
}

async function rowKeys(dialog: Locator) {
  return dialog.locator(rowSelector).evaluateAll((rows) => rows.map((item) => item.getAttribute("data-key")))
}

async function result(page: Page) {
  return JSON.parse((await page.locator("#adapt-filters-dialog-demo-result").textContent())!) as {
    values: Record<string, { operator: string; values: string[] }[]>
    visibleKeys: string[]
  }
}

test.beforeEach(async ({ page }) => {
  await page.goto("/index.html#/adapt-filters-dialog")
  await page.waitForSelector("html[data-ready=true]")
})

test("adapt-filters-dialog: opens with live editors, protects mandatory fields and traps focus", async ({ page }) => {
  const dialog = await openDialog(page)
  await expect(dialog.getByText("Filter Values and Visibility", { exact: true })).toBeVisible()
  await expect(dialog.getByRole("button", { name: "Reset", exact: true })).toBeDisabled()
  await expect(row(dialog, "name").getByRole("textbox", { name: "Name", exact: true })).toHaveValue("Notebook")
  await expect(row(dialog, "name").getByRole("button", { name: /Remove/ })).toHaveCount(0)
  await expect(row(dialog, "name").getByRole("button", { name: /Hide on Filter Bar/ })).toBeDisabled()
  for (let index = 0; index < 8; index++) {
    await page.keyboard.press("Tab")
    await expect.poll(() => dialog.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  }
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.locator("#adapt-filters-dialog-demo-open")).toBeFocused()
})

test("adapt-filters-dialog: hide, show, add and remove announce changes and OK applies", async ({ page }) => {
  const dialog = await openDialog(page)
  // AdaptFiltersDialog's own status channel; SegmentedButton has an independent
  // assertive alert in the same modal (INTEGRATION cause 1: selector scope).
  const announcement = dialog.locator('[role="status"][aria-live="assertive"]')
  await expect(announcement).toHaveCount(1)
  await expect(announcement).toHaveAttribute("aria-atomic", "true")
  await row(dialog, "category").getByRole("button", { name: /Hide on Filter Bar/ }).click()
  await expect(announcement).toHaveText("Filter Category is now hidden")
  // A hidden field with an active value remains editable in the List view.
  await expect(row(dialog, "category").getByRole("textbox", { name: "Category", exact: true })).toHaveValue("Office")
  await row(dialog, "category").getByRole("button", { name: /Show on Filter Bar/ }).click()
  await expect(announcement).toHaveText("Filter Category is now visible")
  const add = dialog.getByRole("combobox", { name: /Add Filter/ })
  await add.fill("Country")
  await add.press("Enter")
  await expect(row(dialog, "country")).toBeVisible()
  await expect(row(dialog, "country").getByRole("textbox", { name: "Country", exact: true })).toBeFocused()
  await expect(announcement).toHaveText("Filter Country added")
  await row(dialog, "country").getByRole("textbox", { name: "Country", exact: true }).fill("Germany")
  await row(dialog, "category").getByRole("button", { name: /Remove Filter/ }).click()
  await expect(row(dialog, "category")).toHaveCount(0)
  await expect(announcement).toHaveText("Filter Category removed")
  await expect(page.locator("#adapt-filters-dialog-demo-applies")).toHaveText("Applied 0 times")
  await dialog.getByRole("button", { name: "OK", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const applied = await result(page)
  expect(applied.visibleKeys).toEqual(["name", "supplier", "country"])
  expect(applied.values.country[0].values).toEqual(["Germany"])
  expect(applied.values.category ?? []).toEqual([])
  await expect(page.locator("#adapt-filters-dialog-demo-applies")).toHaveText("Applied 1 times")
})

