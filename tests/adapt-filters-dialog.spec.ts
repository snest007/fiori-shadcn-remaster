  dialog = await openDialog(page)
  await row(dialog, "supplier").getByRole("button", { name: /Remove Filter/ }).click()
  await expect(row(dialog, "category")).toBeFocused()
  const add = dialog.getByRole("combobox", { name: "Add Filter", exact: true })
