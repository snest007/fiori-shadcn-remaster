import { expect, test } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.goto(`/index.html`)
  await page.waitForSelector("html[data-ready=true]")
})

test("filter-bar: labelled fields, search, Go and Adapt Filters with the active count", async ({ page }) => {
  const fb = page.locator("#filter-bar-demo")
  await expect(fb).toHaveAttribute("role", "search")
  await expect(fb.getByLabel("Sales Order")).toBeVisible()
  await expect(fb.getByRole("searchbox", { name: "Search" })).toBeVisible()
  await expect(fb.getByRole("button", { name: "Adapt Filters" })).toHaveText("Adapt Filters")
  await fb.getByLabel("Sales Order").fill("500")
  await expect(fb.getByRole("button", { name: "Adapt Filters (1)" })).toBeVisible()
  await fb.getByRole("button", { name: "Go" }).click()
  await expect(page.locator("#filter-bar-demo-runs")).toHaveText("Searched 1 times")
  // Enter in a filter field or the search runs Go.
  await fb.getByLabel("Changed On").press("Enter")
  await fb.getByRole("searchbox").press("Enter")
  await expect(page.locator("#filter-bar-demo-runs")).toHaveText("Searched 3 times")
})

test("filter-bar: hide / show the filter bar; collapsed shows the filter summary", async ({ page }) => {
  const fb = page.locator("#filter-bar-demo")
  const toggle = fb.locator("[data-slot=filter-bar-toggle]")
  await expect(toggle).toHaveAttribute("aria-expanded", "true")
  await expect(toggle).toHaveAccessibleName("Hide Filter Bar")
  await toggle.click()
  await expect(fb.getByLabel("Sales Order")).toBeHidden()
  await expect(fb.locator("[data-slot=filter-bar-summary]")).toHaveText("No filters active")
  await toggle.click()
  await fb.getByLabel("Sales Order").fill("500")
  await fb.getByLabel("Changed On").fill("today")
  await toggle.click()
  await expect(fb.locator("[data-slot=filter-bar-summary]")).toHaveText("2 filters active: Sales Order, Changed On")
  await expect(toggle).toHaveAccessibleName("Show Filter Bar")
})

test("filter-bar: guideline layout — label above each field, equal columns, buttons at the row end", async ({ page }) => {
  const items = page.locator("#filter-bar-demo [data-slot=filter-bar-item]")
  const boxes = await items.evaluateAll((els) => els.map((e) => e.getBoundingClientRect().toJSON()))
  expect(new Set(boxes.map((b) => Math.round(b.width))).size).toBe(1)
  const label = (await items.first().locator("label").boundingBox())!
  const field = (await items.first().locator("[data-slot=select-trigger-wrapper]").boundingBox())!
  expect(label.y + label.height).toBeLessThanOrEqual(field.y + 1)
  // Go / Adapt Filters close the row at its end edge (on the fields' row when it fits, else wrapped).
  const adapt = (await page.locator("#filter-bar-demo").getByRole("button", { name: /Adapt Filters/ }).boundingBox())!
  const content = (await page.locator("#filter-bar-demo .fiori-filter-bar__content").boundingBox())!
  expect(Math.abs(adapt.x + adapt.width - (content.x + content.width))).toBeLessThanOrEqual(1)
  const go = (await page.locator("#filter-bar-demo").getByRole("button", { name: "Go" }).boundingBox())!
  expect(go.x).toBeLessThan(adapt.x)
})

test("filter-bar: built-in dialog stages values and visibility; Cancel reverts and OK updates counts", async ({ page }) => {
  const fb = page.locator("#filter-bar-demo")
  const dialog = page.locator("#filter-bar-demo-adapt-dialog")
  await fb.getByLabel("Changed On", { exact: true }).fill("today")
  await fb.getByRole("button", { name: "Adapt Filters (1)", exact: true }).click()
  await expect(dialog).toBeVisible()
  const changed = dialog.locator("[data-slot=adapt-filters-row][data-key=changed]")
  await changed.getByRole("textbox", { name: "Changed On", exact: true }).fill("tomorrow")
  await changed.getByRole("button", { name: /Hide on Filter Bar/ }).click()
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(fb.getByLabel("Changed On", { exact: true })).toHaveValue("today")
  await expect(fb.locator("[data-slot=filter-bar-summary]")).toHaveText("1 filter active")
  await fb.getByRole("button", { name: "Adapt Filters (1)", exact: true }).click()
  await expect(dialog).toBeVisible()
  await changed.getByRole("textbox", { name: "Changed On", exact: true }).fill("tomorrow")
  await changed.getByRole("button", { name: /Hide on Filter Bar/ }).click()
  await dialog.getByRole("button", { name: "OK", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(fb.getByLabel("Changed On", { exact: true })).toHaveCount(0)
  await expect(fb.locator("[data-slot=filter-bar-summary]")).toHaveText("1 filter active (1 hidden)")
  await expect(page.locator("#filter-bar-demo-runs")).toHaveText("Searched 0 times")
  await fb.getByRole("searchbox", { name: "Search", exact: true }).fill("sales")
  await expect(fb.getByRole("button", { name: "Adapt Filters (2)", exact: true })).toBeVisible()
  await expect(fb.locator("[data-slot=filter-bar-summary]")).toHaveText("2 filters active (1 hidden)")
  await fb.getByRole("button", { name: "Hide Filter Bar", exact: true }).click()
  await expect(fb.locator("[data-slot=filter-bar-summary]")).toHaveText("2 filters active: Search Terms, Changed On")
})

test("filter-bar: dialog Sort order applies to bar fields", async ({ page }) => {
  const fb = page.locator("#filter-bar-demo")
  await fb.getByRole("button", { name: "Adapt Filters", exact: true }).click()
  const dialog = page.locator("#filter-bar-demo-adapt-dialog")
  await expect(dialog).toBeVisible()
  await dialog.getByRole("option", { name: "Sort", exact: true }).click()
  await expect(dialog).toHaveAttribute("data-mode", "sort")
  const changed = dialog.locator("[data-slot=adapt-filters-row][data-key=changed]")
  await changed.focus()
  await changed.press("Control+Home")
  await expect.poll(() => dialog.locator("[data-slot=adapt-filters-row]").evaluateAll((rows) => rows.map((row) => row.getAttribute("data-key")))).toEqual(["changed", "status", "order"])
  await dialog.getByRole("button", { name: "OK", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => fb.locator("[data-slot=filter-bar-item]").evaluateAll((rows) => rows.map((row) => row.getAttribute("data-filter-key")))).toEqual(["changed", "status", "order"])
})

test("filter-bar: live mode searches committed bar and dialog conditions once", async ({ page }) => {
  const fb = page.locator("#filter-bar-demo")
  const runs = page.locator("#filter-bar-demo-runs")
  await page.locator("#filter-bar-demo-live").click()
  await expect(fb.getByRole("button", { name: "Go", exact: true })).toHaveCount(0)
  await expect(runs).toHaveText("Searched 0 times")
  await fb.getByLabel("Sales Order", { exact: true }).fill("500")
  await expect(runs).toHaveText("Searched 1 times")
  await fb.getByRole("button", { name: "Adapt Filters (1)", exact: true }).click()
  const dialog = page.locator("#filter-bar-demo-adapt-dialog")
  await expect(dialog).toBeVisible()
  await dialog.getByRole("textbox", { name: "Sales Order", exact: true }).fill("600")
  await expect(runs).toHaveText("Searched 1 times")
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(runs).toHaveText("Searched 1 times")
  await fb.getByRole("button", { name: "Adapt Filters (1)", exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole("textbox", { name: "Sales Order", exact: true }).fill("700")
  await dialog.getByRole("button", { name: "OK", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(runs).toHaveText("Searched 2 times")
  await expect(fb.getByLabel("Sales Order", { exact: true })).toHaveValue("700")
})

test("filter-bar: required filters stay visible and Go validates before searching", async ({ page }) => {
  const fb = page.locator("#filter-bar-required-demo")
  const field = fb.getByRole("textbox", { name: "Company Code", exact: true })
  await expect(field).toBeVisible()
  await fb.getByRole("button", { name: "Go", exact: true }).click()
  await expect(field).toHaveAttribute("aria-invalid", "true")
  await expect(field).toBeFocused()
  await expect(fb).toContainText("Company Code is a required field.")
  await expect(page.locator("#filter-bar-required-demo-runs")).toHaveText("Searched 0 times")
  await field.fill("1000")
  await fb.getByRole("button", { name: "Go", exact: true }).click()
  await expect(field).not.toHaveAttribute("aria-invalid", "true")
  await expect(page.locator("#filter-bar-required-demo-runs")).toHaveText("Searched 1 times")
})

