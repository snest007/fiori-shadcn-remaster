test("menu checks: trigger Space does not activate the first submenu owner on its keyup", async ({ page }) => {
  const trigger = demo(page).locator("#menu-check-mode-first-owner-trigger")
  const menu = page.getByRole("menu", { name: "First owner preferences", exact: true })
  const owner = menu.getByRole("menuitemcheckbox", { name: "First owner", exact: true })
  const submenu = page.getByRole("menu", { name: "First owner children", exact: true })
  const child = submenu.getByRole("menuitem", { name: "First child", exact: true })
  await trigger.focus()
  await expect(trigger).toBeFocused()
  await page.keyboard.down("Space")
  await expect(owner).toBeFocused()
  await expect(submenu).toHaveCount(0)
  await page.keyboard.up("Space")
  await expect(owner).toBeFocused()
  await expect(owner).toHaveAttribute("aria-expanded", "false")
  await expect(submenu).toHaveCount(0)
  // A distinct Space stroke belongs to the focused owner and opens on keyup.
  await page.keyboard.down("Space")
  await expect(submenu).toHaveCount(0)
  await page.keyboard.up("Space")
  await expect(child).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(submenu).toHaveCount(0)
  await expect(owner).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(menu).toHaveCount(0)
  await expect(trigger).toBeFocused()
  // The handoff guard must preserve independent Enter and mouse activation.
  for (const activation of ["Enter", "click"] as const) {
    if (activation === "Enter") await page.keyboard.press("Enter")
    else await trigger.click()
    await expect(owner).toBeFocused()
    await expect(submenu).toHaveCount(0)
    if (activation === "Enter") await page.keyboard.press("Enter")
    else await owner.click()
    await expect(child).toBeFocused()
    await page.keyboard.press("Escape")
    await expect(owner).toBeFocused()
    await page.keyboard.press("Escape")
    await expect(menu).toHaveCount(0)
    await expect(trigger).toBeFocused()
  }
})

test("menu checks: disabled checked submenu owners behave as checked leaves in single and multiple groups", async ({ page }) => {
  await open(page)
  await expect(radio(page, "Single owner peer")).toHaveAttribute("aria-checked", "false")
  for (const [role, name, child] of [
    ["menuitemradio", "Disabled single owner", "Unavailable single child"],
    ["menuitemcheckbox", "Disabled multiple owner", "Unavailable multiple child"],
  ] as const) {
    const owner = rootMenu(page).getByRole(role, { name, exact: true })
    await expect(owner).toHaveAttribute("aria-checked", "true")
    await expect(owner).toHaveAttribute("aria-disabled", "true")
    await expect(owner.locator(".fiori-menu-item__checked")).toHaveCount(1)
    await expect(owner.locator(".fiori-menu-item__submenu")).toHaveCount(0)
    for (const attribute of ["aria-haspopup", "aria-expanded", "aria-controls"]) await expect(owner).not.toHaveAttribute(attribute)
    await expect(page.getByRole("menuitem", { name: child, exact: true })).toHaveCount(0)
    await focus(owner)
    for (const key of ["ArrowRight", "Enter", "Space", "Shift+Enter", "Shift+Space"]) {
      await page.keyboard.press(key)
      await expect(owner).toBeFocused()
      await expect(owner).toHaveAttribute("aria-checked", "true")
      await expect(page.getByRole("menuitem", { name: child, exact: true })).toHaveCount(0)
    }
    await owner.click({ force: true })
    await expect(owner).toHaveAttribute("aria-checked", "true")
    await expect(page.getByRole("menuitem", { name: child, exact: true })).toHaveCount(0)
  }
  await expect(result(page)).toHaveText("No checks")
})

test("menu checks: nested Escape/Left close only their owning level and modified keys do nothing", async ({ page }) => {
  await open(page)
  await focus(checkbox(page, "Nested"))
  await page.keyboard.press("Shift+ArrowRight")
  await expect(nestedMenu(page)).toHaveCount(0)
  await page.keyboard.press("ArrowRight")
  const deeper = nestedMenu(page).getByRole("menuitem", { name: "Deeper", exact: true })
  await focus(deeper)
  await page.keyboard.press("ArrowRight")
  const child = page.getByRole("menuitem", { name: "Deep child", exact: true })
  await expect(child).toBeFocused()
  for (const key of ["Shift+Escape", "Control+ArrowLeft"]) {
    await page.keyboard.press(key)
    await expect(child).toBeFocused()
  }
  await page.keyboard.press("Escape")
  await expect(child).toHaveCount(0)
  await expect(deeper).toBeFocused()
  await expect(rootMenu(page)).toBeVisible()
  await page.keyboard.press("ArrowLeft")
  await expect(nestedMenu(page)).toHaveCount(0)
  await expect(checkbox(page, "Nested")).toBeFocused()
})

