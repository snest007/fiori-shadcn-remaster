import { expect, test, type Page } from "@playwright/test"

const demo = (page: Page) => page.locator("#menu-check-mode-demo")
const rootMenu = (page: Page) => page.getByRole("menu", { name: "Check mode preferences", exact: true })
const nestedMenu = (page: Page) => page.getByRole("menu", { name: "Nested preferences", exact: true })
const result = (page: Page) => demo(page).locator("#menu-check-mode-result")
const radio = (page: Page, name: string) => rootMenu(page).getByRole("menuitemradio", { name, exact: true })
const checkbox = (page: Page, name: string) => rootMenu(page).getByRole("menuitemcheckbox", { name, exact: true })
async function open(page: Page) {
  await demo(page).locator("#menu-check-mode-trigger").click()
  await expect(rootMenu(page)).toBeVisible()
  await expect(radio(page, "First")).toBeFocused()
}
async function focus(item: ReturnType<typeof checkbox>) { await item.focus(); await expect(item).toBeFocused() }

test.beforeEach(async ({ page }) => {
  await page.goto("/index.html#/menu")
  await page.waitForSelector("html[data-ready=true]")
})

test("menu checks: group roles, labels, explicit separators and last initial single check", async ({ page }) => {
  await open(page)
  await expect(rootMenu(page).getByRole("group", { name: "Contains Selectable Items", exact: true })).toHaveCount(1)
  await expect(rootMenu(page).getByRole("group", { name: "Contains Multi-Selectable Items", exact: true })).toHaveCount(1)
  await expect(rootMenu(page).getByRole("group", { name: "Contains Non-Selectable Items", exact: true })).toHaveCount(1)
  await expect(rootMenu(page).getByRole("separator")).toHaveCount(1)
  await expect(radio(page, "First")).toHaveAttribute("aria-checked", "false")
  await expect(radio(page, "Last")).toHaveAttribute("aria-checked", "true")
  await expect(radio(page, "Separate")).toHaveAttribute("aria-checked", "true")
  await expect(rootMenu(page).getByRole("menuitem", { name: "Ordinary", exact: true })).not.toHaveAttribute("aria-checked")
  await expect(result(page)).toHaveText("No checks")
})

test("menu checks: single toggles off, silently clears direct siblings and keeps separate groups", async ({ page }) => {
  await open(page)
  await radio(page, "Last").click({ modifiers: ["Shift"] })
  await expect(radio(page, "Last")).toHaveAttribute("aria-checked", "false")
  await radio(page, "First").click({ modifiers: ["Shift"] })
  await expect(radio(page, "First")).toHaveAttribute("aria-checked", "true")
  await radio(page, "Third").click({ modifiers: ["Shift"] })
  await expect(radio(page, "First")).toHaveAttribute("aria-checked", "false")
  await expect(radio(page, "Third")).toHaveAttribute("aria-checked", "true")
  await expect(radio(page, "Separate")).toHaveAttribute("aria-checked", "true")
  await expect(result(page)).toHaveText("Last:false,First:true,Third:true")
})

test("menu checks: multiple checks are independent and mouse Shift remains effective with Ctrl", async ({ page }) => {
  await open(page)
  // macOS maps a physical Control-click to contextmenu. Dispatch the click UI5 receives.
  await checkbox(page, "Grid").dispatchEvent("click", { shiftKey: true, ctrlKey: true })
  await expect(checkbox(page, "Grid")).toHaveAttribute("aria-checked", "true")
  await expect(checkbox(page, "Copy preference Ctrl+C")).toHaveAttribute("aria-checked", "true")
  await checkbox(page, "Copy preference Ctrl+C").click({ modifiers: ["Shift"] })
  await expect(checkbox(page, "Copy preference Ctrl+C")).toHaveAttribute("aria-checked", "false")
  await expect(checkbox(page, "Grid")).toHaveAttribute("aria-checked", "true")
  await expect(result(page)).toHaveText("Grid:true,Copy preference:false")
})

