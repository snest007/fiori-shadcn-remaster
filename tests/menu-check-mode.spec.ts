test("menu checks: root page navigation uses visible height and clamps boundaries", async ({ page }) => {
  await demo(page).locator("#menu-check-mode-pages-trigger").click()
  const menu = page.getByRole("menu", { name: "Page preferences", exact: true })
  const items = menu.getByRole("menuitemcheckbox")
  await expect(items.first()).toBeFocused()
  const step = await menu.evaluate((element) => Math.round(element.getBoundingClientRect().height / element.querySelector<HTMLElement>('[role^="menuitem"]')!.offsetHeight) - 1)
  await page.keyboard.press("PageDown")
  await expect(items.nth(step)).toBeFocused()
  await page.keyboard.press("PageUp")
  await expect(items.first()).toBeFocused()
  await page.keyboard.press("End")
  await expect(items.last()).toBeFocused()
  await page.keyboard.press("PageDown")
  await expect(items.last()).toBeFocused()
})

test("menu checks: root hover waits 300ms and nested hover focuses without opening", async ({ page }) => {
  await open(page)
  await page.keyboard.press("ArrowDown") // Hover must keep the owner focused after keyboard use too.
  await expect(radio(page, "Last")).toBeFocused()
  await page.clock.install()
  await page.clock.pauseAt(new Date())
  const parent = checkbox(page, "Nested")
  await parent.dispatchEvent("pointermove", { pointerType: "mouse" })
  await expect(parent).toBeFocused()
  await page.clock.fastForward(299)
  await expect(nestedMenu(page)).toHaveCount(0)
  await page.clock.fastForward(1)
  await expect(nestedMenu(page)).toBeVisible()
  await expect(parent).toBeFocused()
  const deeper = nestedMenu(page).getByRole("menuitem", { name: "Deeper", exact: true })
  await deeper.dispatchEvent("pointermove", { pointerType: "mouse" })
  await expect(deeper).toBeFocused()
  await page.clock.fastForward(1000)
  await expect(page.getByRole("menuitem", { name: "Deep child", exact: true })).toHaveCount(0)
})

