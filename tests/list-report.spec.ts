import { expect, test } from "@playwright/test"

test.beforeEach(async ({ page }) => {
  await page.goto(`/block.html?name=list-report`)
  await page.waitForSelector("html[data-ready=true]")
})

test("list-report: floorplan anatomy — variant title, filter bar in the header, table with count", async ({ page }) => {
  const lr = page.locator("#list-report")
  await expect(page.getByRole("main", { name: "Manage Products" })).toBeVisible()
  await expect(lr.getByRole("heading", { level: 1, name: "Standard" })).toBeVisible()
  const header = lr.locator("[data-slot=dynamic-page-header]")
  await expect(header.getByRole("search")).toBeVisible()
  await expect(header.getByRole("searchbox", { name: "Search" })).toBeVisible()
  await expect(lr.getByRole("heading", { name: "Products (12)" })).toBeVisible()
  await expect(lr.getByRole("grid", { name: "Products (12)" })).toBeVisible()
  // The title sits above the header, the header above the table.
  const title = (await lr.locator("[data-slot=dynamic-page-title]").boundingBox())!
  const hdr = (await header.boundingBox())!
  const table = (await lr.getByRole("grid").boundingBox())!
  expect(title.y + title.height).toBeLessThanOrEqual(hdr.y + 1)
  expect(hdr.y + hdr.height).toBeLessThan(table.y)
})

test("list-report: Go applies the filters and updates the count", async ({ page }) => {
  const lr = page.locator("#list-report")
  await lr.getByLabel("Supplier").fill("depot")
  await expect(lr.getByRole("heading", { name: "Products (12)" })).toBeVisible()
  await lr.getByRole("button", { name: "Go" }).click()
  await expect(lr.getByRole("heading", { name: "Products (3)" })).toBeVisible()
  await expect(lr.getByRole("button", { name: "Adapt Filters (1)" })).toBeVisible()
  await lr.getByRole("searchbox").fill("scissors")
  await lr.getByRole("searchbox").press("Enter")
  await expect(lr.getByRole("heading", { name: "Products (1)" })).toBeVisible()
})

test("list-report: header snaps on scroll and shows the filter summary in the title", async ({ page }) => {
  const lr = page.locator("#list-report")
  await page.setViewportSize({ width: 1280, height: 500 })
  await lr.getByLabel("Supplier").fill("o")
  await lr.locator(".fiori-dynamic-page__scroll").first().evaluate((e) => (e.scrollTop = 400))
  await expect(lr).toHaveAttribute("data-header-snapped", "")
  await expect(lr.locator("[data-slot=list-report-summary]")).toHaveText("1 filter active: Supplier")
  await expect(lr.getByRole("search")).toBeHidden()
})

test("list-report: selecting rows shows the footer with the mass action", async ({ page }) => {
  const lr = page.locator("#list-report")
  const footer = lr.locator("[data-slot=dynamic-page-footer]")
  await expect(lr).not.toHaveAttribute("data-show-footer")
  await lr.getByRole("row", { name: /Premium Scissors/ }).getByRole("checkbox").click()
  await lr.getByRole("row", { name: /Tea\/Coffee Mugs/ }).getByRole("checkbox").click()
  await expect(lr).toHaveAttribute("data-show-footer", "")
  await expect(footer.getByRole("button", { name: "Approve (2)" })).toBeVisible()
  await expect(lr.getByRole("button", { name: "Delete" })).toBeEnabled()
  await footer.getByRole("button", { name: "Cancel" }).click()
  await expect(lr).not.toHaveAttribute("data-show-footer")
})

test("list-report: Save As persists the default view and applies it automatically after reload", async ({ page }) => {
  const lr = page.locator("#list-report")
  const views = lr.locator("#list-report-variants")
  await lr.getByLabel("Supplier", { exact: true }).fill("depot")
  await lr.getByRole("searchbox", { name: "Search", exact: true }).fill("scissors")
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("Modified view Standard.")
  await expect(views.locator(".fiori-vm-modified")).toHaveText("*")
  await views.getByTitle("Select View", { exact: true }).click()
  const list = page.getByRole("dialog", { name: "My Views", exact: true })
  await expect(list).toBeVisible()
  await expect(list.getByRole("button", { name: "Save", exact: true })).toHaveCount(0)
  await list.getByRole("button", { name: "Save As", exact: true }).click()
  const save = page.getByRole("dialog", { name: "Save View", exact: true })
  await expect(save).toBeVisible()
  await save.getByRole("textbox", { name: "View:", exact: true }).fill("My View")
  await save.getByRole("checkbox", { name: "Set as Default", exact: true }).check()
  await save.getByRole("checkbox", { name: "Apply Automatically", exact: true }).check()
  await save.getByRole("button", { name: "Save", exact: true }).click()
  await expect(save).toHaveCount(0)
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("View My View.")
  await expect(lr.getByRole("heading", { name: "Products (1)", exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("fiori-list-report-variants") ?? "[]").find((item: { default?: boolean }) => item.default)?.title)).toBe("My View")
  await page.reload()
  await page.waitForSelector("html[data-ready=true]")
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("View My View.")
  await expect(lr.getByLabel("Supplier", { exact: true })).toHaveValue("depot")
  await expect(lr.getByRole("searchbox", { name: "Search", exact: true })).toHaveValue("scissors")
  await expect(lr.getByRole("heading", { name: "Products (1)", exact: true })).toBeVisible()
  await expect(views.locator(".fiori-vm-modified")).toBeEmpty()
})

test("list-report: Manage renames a view, changes the default and deletes the selected view", async ({ page }) => {
  const lr = page.locator("#list-report")
  const views = lr.locator("#list-report-variants")
  await views.getByTitle("Select View", { exact: true }).click()
  await page.getByRole("dialog", { name: "My Views", exact: true }).getByRole("button", { name: "Save As", exact: true }).click()
  const save = page.getByRole("dialog", { name: "Save View", exact: true })
  await expect(save).toBeVisible()
  await save.getByRole("textbox", { name: "View:", exact: true }).fill("My View")
  await save.getByRole("checkbox", { name: "Set as Default", exact: true }).check()
  await save.getByRole("button", { name: "Save", exact: true }).click()
  await expect(save).toHaveCount(0)
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("View My View.")
  await views.getByTitle("Select View", { exact: true }).click()
  await page.getByRole("dialog", { name: "My Views", exact: true }).getByRole("button", { name: "Manage", exact: true }).click()
  const manage = page.getByRole("dialog", { name: "Manage Views", exact: true })
  await expect(manage).toBeVisible()
  const own = manage.locator("[data-variant-key]").filter({ has: page.getByRole("textbox", { name: "View", exact: true }) })
  await own.getByRole("textbox", { name: "View", exact: true }).fill("Renamed View")
  await manage.locator('[data-variant-key="standard"]').getByRole("radio", { name: "Default", exact: true }).click()
  await manage.getByRole("button", { name: "Save", exact: true }).click()
  await expect(manage).toHaveCount(0)
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("View Renamed View.")
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("fiori-list-report-variants") ?? "[]").find((item: { default?: boolean }) => item.default)?.key)).toBe("standard")
  await page.reload()
  await page.waitForSelector("html[data-ready=true]")
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("View Standard.")
  await views.getByTitle("Select View", { exact: true }).click()
  await page.getByRole("dialog", { name: "My Views", exact: true }).getByRole("option", { name: "Renamed View", exact: true }).click()
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("View Renamed View.")
  await views.getByTitle("Select View", { exact: true }).click()
  await page.getByRole("dialog", { name: "My Views", exact: true }).getByRole("button", { name: "Manage", exact: true }).click()
  await expect(manage).toBeVisible()
  const selected = manage.locator("[data-variant-key]").filter({ has: page.getByRole("textbox", { name: "View", exact: true }) })
  await selected.getByRole("button", { name: "Delete View", exact: true }).click()
  await expect(selected).toHaveCount(0)
  await manage.getByRole("button", { name: "Save", exact: true }).click()
  await expect(manage).toHaveCount(0)
  await expect(views.getByTitle("Select View", { exact: true })).toHaveAccessibleName("View Standard.")
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem("fiori-list-report-variants") ?? "[]").map((item: { key: string }) => item.key))).toEqual(["standard"])
})


