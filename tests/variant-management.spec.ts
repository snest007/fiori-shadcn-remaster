import { expect, test, type Locator, type Page } from "@playwright/test"

const command = process.platform === "darwin" ? "Meta" : "Control"
const demo = (page: Page) => page.locator("#variant-management-demo")
const title = (page: Page) => demo(page).locator(".fiori-vm-trigger")
const trigger = (page: Page) => demo(page).getByTitle("Select View", { exact: true })
const viewDialog = (page: Page) => demo(page).getByRole("dialog", { name: "My Views", exact: true })
const saveDialog = (page: Page) => demo(page).getByRole("dialog", { name: "Save View", exact: true })
const manageDialog = (page: Page) => demo(page).getByRole("dialog", { name: "Manage Views", exact: true })
const row = (dialog: Locator, key: string) => dialog.locator(`[data-variant-key="${key}"]`)
const events = async (page: Page) => JSON.parse(await demo(page).locator("#variant-management-demo-events").innerText()) as { type: string; payload?: Record<string, unknown> }[]
const state = async (page: Page) => JSON.parse(await demo(page).locator("#variant-management-demo-state").innerText()) as { selectedKey: string; defaultKey: string; items: { key: string; title: string; favorite?: boolean; executeOnSelect?: boolean; contexts?: { role: string[] } }[] }

async function openList(page: Page) {
  await trigger(page).click()
  await expect(viewDialog(page)).toBeVisible()
  return viewDialog(page)
}

async function openSave(page: Page) {
  const list = await openList(page)
  await list.getByRole("button", { name: "Save As", exact: true }).click()
  const dialog = saveDialog(page)
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole("textbox")).toBeFocused()
  return dialog
}

async function openManage(page: Page) {
  const list = await openList(page)
  await list.getByRole("button", { name: "Manage", exact: true }).click()
  const dialog = manageDialog(page)
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole("searchbox")).toBeFocused()
  return dialog
}

