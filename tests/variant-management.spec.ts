test("variant-management: Manage emits one aggregate delta and persists through the app", async ({ page }) => {
  const dialog = await openManage(page)
  await row(dialog, "sales").getByRole("textbox").fill("My Sales")
  await row(dialog, "sales").getByRole("checkbox").check()
  await row(dialog, "operations").getByTitle("Selected as Favorite", { exact: true }).click()
  await expect(row(dialog, "operations").getByTitle("Unselected as Favorite", { exact: true })).toBeVisible()
  await row(dialog, "dormant").getByRole("radio").check()
  await expect(row(dialog, "dormant").getByRole("radio")).toBeChecked()
  await expect(row(dialog, "dormant").getByTitle("Selected as Favorite", { exact: true })).toBeVisible()
  await row(dialog, "view-6").getByRole("textbox").fill("Deleted rename")
  await row(dialog, "view-6").getByRole("checkbox").check()
  await row(dialog, "view-6").getByTitle("Selected as Favorite", { exact: true }).click()
  await row(dialog, "view-6").getByTitle("Delete View", { exact: true }).click()
  await expect(row(dialog, "view-6")).toHaveCount(0)
  await dialog.getByRole("button", { name: "Save", exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect.poll(() => events(page)).toEqual([{ type: "manage", payload: {
    renamed: [{ key: "sales", name: "My Sales" }], deleted: ["view-6"],
    exe: [{ key: "sales", exe: true }], fav: [{ key: "operations", visible: false }, { key: "dormant", visible: true }], def: "dormant",
  } }])
  const persisted = await state(page)
  expect(persisted.defaultKey).toBe("dormant")
  expect(persisted.items.find((item) => item.key === "sales")).toMatchObject({ title: "My Sales", executeOnSelect: true })
  expect(persisted.items.some((item) => item.key === "view-6")).toBe(false)
  await expect(title(page)).toContainText("My Sales")
})

