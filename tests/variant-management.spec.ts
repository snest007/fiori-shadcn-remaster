test("variant-management: Manage dialog supports pointer drag, keyboard resize and geometry reset", async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 1200 })
  await demo(page).getByRole("checkbox", { name: "Use short list", exact: true }).check()
  const dialog = await openManage(page)
  await dialog.scrollIntoViewIfNeeded()
  const before = (await dialog.boundingBox())!
  const header = dialog.locator("[data-vm-draggable]")
  const headerBox = (await header.boundingBox())!
  const x = headerBox.x + headerBox.width / 2
  const y = headerBox.y + headerBox.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 32, y + 16)
  await page.mouse.up()
  await expect.poll(async () => (await dialog.boundingBox())!.x).toBeCloseTo(before.x + 32, 1)
  await expect.poll(async () => (await dialog.boundingBox())!.y).toBeCloseTo(before.y + 16, 1)
  const handle = dialog.locator(".fiori-vm-keyboard-handle")
  await handle.focus()
  await expect(handle).toBeFocused()
  const moved = (await dialog.boundingBox())!
  await handle.press("Shift+ArrowRight")
  await expect.poll(async () => (await dialog.boundingBox())!.width).toBeCloseTo(moved.width + 16, 1)
  await handle.press("ArrowLeft")
  await expect.poll(async () => (await dialog.boundingBox())!.x).toBeCloseTo(moved.x - 16, 1)
  await header.dblclick()
  await expect(dialog).toHaveCSS("position", "relative")
  await expect(row(dialog, "sales").getByRole("textbox")).toHaveValue("Sales Orders")
})

