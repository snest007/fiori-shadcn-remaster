import { expect, test, type Locator, type Page } from "@playwright/test"

async function visit(page: Page, kind: string, native = false, suffix = "") {
  await page.goto(`/${native ? "ui5" : "index"}.html?fixtures-phone&interactive&only=${kind}-phone${suffix}`)
  await page.waitForSelector("html[data-ready=true]")
  return page.locator(`#${kind}-phone-demo`)
}
const surface = (page: Page, holder: Locator, native: boolean) => native ? holder : dialog(page, false)
const dialog = (page: Page, native: boolean) => native ? page.locator("ui5-dialog[open]") : page.locator('[role="dialog"]')
const phoneInput = (page: Page, native: boolean) => native ? page.locator("ui5-responsive-popover ui5-input input") : dialog(page, false).locator("input")
const fieldInput = (holder: Locator, kind: string, native: boolean) => native ? holder.locator(`ui5-${kind} input`).first() : holder.locator(`#${kind}-phone-field`)
async function expectDeepFocus(locator: Locator) {
  // List content is projected through UI5's BusyIndicator/Popup slots. Inspect
  // the deepest focused DOM node, including focus beyond the owning shadow root.
  await expect.poll(() => locator.evaluate((element) => {
    let active = document.activeElement
    while (active?.shadowRoot?.activeElement) active = active.shadowRoot.activeElement
    return active === element
  })).toBe(true)
}
async function awaitPhoneRender(holder: Locator, native: boolean) {
  // UI5 Popup open/close and Input edits can schedule owning List renders after
  // the surface first appears. Await its supported lifecycle before the next action.
  if (native) await holder.evaluate(async (element: any) => element.phoneRenderFinished())
}
async function fillPhone(page: Page, holder: Locator, native: boolean, value: string) {
  await phoneInput(page, native).fill(value)
  await awaitPhoneRender(holder, native)
}
async function openField(page: Page, holder: Locator, kind: string, native: boolean) {
  await awaitPhoneRender(holder, native)
  const field = kind === "select" ? holder.getByRole("combobox").first() : fieldInput(holder, kind, native)
  if (native && kind === "multi-input") {
    // MultiInput.js/innerFocusIn expands its Tokenizer before pointerup, shrinking
    // the source input from the token side. Keep a real click inside the overlap.
    const box = (await field.boundingBox())!
    const rtl = await field.evaluate((element) => getComputedStyle(element).direction === "rtl")
    await field.click({ position: { x: box.width * (rtl ? 0.1 : 0.9), y: box.height / 2 } })
  } else {
    await field.click()
  }
  await expect(dialog(page, native)).toBeVisible()
  await expect(dialog(page, native)).toHaveCSS("width", "375px")
  await expect(dialog(page, native)).toHaveCSS("height", "667px")
  await awaitPhoneRender(holder, native)
}

