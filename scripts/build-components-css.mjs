// Concatenates registry/styles/components/*.css into registry/styles/fiori-components.css (one file
// to ship and import). Each component owns its own source file, so parallel work never collides.
import { readFileSync, readdirSync, writeFileSync } from "node:fs"

const dir = "registry/styles/components"
// Shared building blocks first so component files can override them.
const FIRST = ["field.css", "popover.css", "list-item.css", "value-state-message.css"]
const files = readdirSync(dir).filter((f) => f.endsWith(".css"))
const ordered = [...FIRST.filter((f) => files.includes(f)), ...files.filter((f) => !FIRST.includes(f)).sort()]

const indent = (css) => css.trim().split("\n").map((l) => (l ? "  " + l : l)).join("\n")
const out = `/*
 * GENERATED by scripts/build-components-css.mjs from registry/styles/components/*.css — do not edit.
 * Fiori component styles that are too stateful for utility classes. Rules mirror UI5 Web Components'
 * component CSS; values come from fiori.css (--sap* tokens, --fiori-* UI5 parameters).
 *
 * Portions derived from UI5 Web Components 2.28 component styles (dist/generated/themes/*.css.js),
 * © SAP SE or an SAP affiliate company and UI5 contributors, licensed under Apache-2.0.
 * Modified by petalo: rewritten for React markup and --fiori-* parameters.
 * SPDX-License-Identifier: Apache-2.0
 */
@layer components {
${ordered.map((f) => indent(readFileSync(`${dir}/${f}`, "utf8"))).join("\n\n")}
}
`
writeFileSync("registry/styles/fiori-components.css", out)
console.log(`fiori-components.css written (${ordered.length} files)`)
