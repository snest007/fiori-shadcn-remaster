// Generates registry/lib/fiori-illustrations/ from @ui5/webcomponents-fiori (Apache-2.0, © SAP SE).
//
// UI5 stores every illustration as four SVG strings (Scene 320×240, Dialog 160×160, Spot 128×128,
// Dot 45×45) in ES modules, colored only through var(--sapContent_Illustrative_ColorN), so they
// follow the theme without any JS. We emit:
//   <Name>-<Size>.ts      one SVG string per illustration and size (TNT: normal + high-contrast)
//   <Name>.ts             the IllustrationData object for <IllustratedMessage illustration={…}>
//   tnt/…                 the same for SAP's TNT set (V5 + V5/HC; shipped on demand only)
//   types.ts, index.ts    the data type and the list of names
//   registry-items.json   registry items (illustrations-core + one item per illustration), read by
//                         scripts/build-registry-json.mjs
//
// IDs inside the SVGs (masks, clip paths) are rewritten to "__uid__<id>"; IllustratedMessage
// replaces the placeholder with a per-instance prefix, because in light DOM (unlike UI5's shadow
// DOM) two SVGs on one page would otherwise fight over `id="mask0"`. Each module keeps SAP's
// copyright/license header.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"

const require = createRequire(import.meta.url)
const pkgDir = dirname(require.resolve("@ui5/webcomponents-fiori/package.json"))
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version
const dist = join(pkgDir, "dist")
const OUT = "registry/lib/fiori-illustrations"
const SIZES = ["scene", "dialog", "spot", "dot"]
const Cap = (s) => s[0].toUpperCase() + s.slice(1)

// The common empty/error/success states; shipped together as @fiori/illustrations-core.
const CORE = [
  "NoData", "NoEntries", "NoSearchResults", "NoFilterResults", "BeforeSearch", "EmptyList",
  "UnableToLoad", "UnableToUpload", "Tent", "Connection", "PageNotFound", "ErrorScreen",
  "ReloadScreen", "SuccessScreen",
]

const HEADER = (what) =>
  `// GENERATED by scripts/generate-illustrations.mjs, do not edit.\n` +
  `// ${what} from @ui5/webcomponents-fiori@${version}.\n` +
  `// Copyright SAP SE or an SAP affiliate company and OpenUI5 contributors. Licensed under the Apache License, Version 2.0.\n`

// i18n default texts ("There''s no data yet." — MessageFormat doubles apostrophes).
const i18n = Object.fromEntries(
  [...readFileSync(join(dist, "generated/i18n/i18n-defaults.js"), "utf8").matchAll(/const (\w+) = \{ key: "\w+", defaultText: "((?:[^"\\]|\\.)*)" \};/g)].map(
    ([, k, v]) => [k, JSON.parse(`"${v}"`).replace(/''/g, "'")]
  )
)

function readSvg(file) {
  const src = readFileSync(file, "utf8")
  const svg = src.slice(src.indexOf("`") + 1, src.lastIndexOf("`"))
  if (/<script|<style|on[a-z]+=|javascript:/i.test(svg)) throw new Error(`unexpected content in ${file}`)
  return svg
    .replace(/>\s+</g, "><")
    .replace(/\s+/g, " ")
    .replace(/\bid="([^"]+)"/g, 'id="__uid__$1"')
    .replace(/url\(#([^)]+)\)/g, "url(#__uid__$1)")
    .replace(/href="#([^"]+)"/g, 'href="#__uid__$1"')
    // UI5 fills these two classes from patterns defined once in its shadow root; IllustratedMessage
    // renders the same patterns per instance under the "__uid__" prefix.
    .replace(/class="(sapIllus_Pattern(?:Shadow|Highlight))"/g, 'class="$1" fill="url(#__uid__$1)"')
    .trim()
}

// Parses dist/illustrations/<Name>.js: which SVG module backs each size, plus title/subtitle keys.
function readEntry(file) {
  const src = readFileSync(file, "utf8")
  const sizes = {}
  for (const [, size, path] of src.matchAll(/import (\w+)Svg from "\.\/([^"]+)\.js"/g)) sizes[size] = path
  const titleKey = src.match(/const title = (\w+);/)?.[1]
  const subtitleKey = src.match(/const subtitle = (\w+);/)?.[1]
  return { sizes, title: titleKey && i18n[titleKey], subtitle: subtitleKey && i18n[subtitleKey] }
}

const kebab = (s) => s.replace(/_/g, "-").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase()

rmSync(OUT, { recursive: true, force: true })
mkdirSync(join(OUT, "tnt"), { recursive: true })

writeFileSync(
  join(OUT, "types.ts"),
  `${HEADER("Types for the SAP Fiori illustrations")}
export type IllustrationSize = "scene" | "dialog" | "spot" | "dot"

/** One illustration in its four sizes. SVG strings contain "__uid__" placeholders for their ids. */
export type IllustrationData = {
  name: string
  set: "fiori" | "tnt"
  /** Default English texts (UI5's i18n defaults); TNT illustrations have none. */
  title?: string
  subtitle?: string
  scene: string
  dialog: string
  spot: string
  dot: string
  /** High-contrast variants (TNT only); used in sap_horizon_hcb / sap_horizon_hcw. */
  hc?: { scene: string; dialog: string; spot: string; dot: string }
}
`
)

const items = []
const fioriNames = []
const tntNames = []

// --- Fiori set (V4 collection; the same SVGs serve all four Horizon themes) -------------------
const fioriDir = join(dist, "illustrations")
for (const file of readdirSync(fioriDir).filter((f) => /^[A-Z]\w*\.js$/.test(f) && f !== "AllIllustrations.js").sort()) {
  const name = file.replace(/\.js$/, "")
  const entry = readEntry(join(fioriDir, file))
  const files = []
  const imports = []
  const fields = []
  const emitted = new Map()
  for (const size of SIZES) {
    const srcPath = entry.sizes[size]
    if (!srcPath) throw new Error(`${name}: no ${size}`)
    // sapIllus-Spot-SuccessBalloon -> SuccessBalloon-Spot
    const [, srcSize, srcName] = srcPath.match(/^sapIllus-(\w+?)-(.+)$/)
    const mod = `${srcName}-${srcSize}`
    if (!emitted.has(mod)) {
      writeFileSync(join(OUT, `${mod}.ts`), `${HEADER(`SAP illustration "${srcName}" (${srcSize})`)}\nexport default ${JSON.stringify(readSvg(join(fioriDir, `${srcPath}.js`)))}\n`)
      const id = `${srcSize.toLowerCase()}Svg`
      emitted.set(mod, id)
      imports.push(`import ${id} from "./${mod}"`)
      files.push(`${OUT}/${mod}.ts`)
    }
    fields.push(`  ${size}: ${emitted.get(mod)},`)
  }
  writeFileSync(
    join(OUT, `${name}.ts`),
    `${HEADER(`SAP illustration "${name}"`)}
import type { IllustrationData } from "./types"
${imports.join("\n")}

const ${name}: IllustrationData = {
  name: ${JSON.stringify(name)},
  set: "fiori",
  title: ${JSON.stringify(entry.title)},
  subtitle: ${JSON.stringify(entry.subtitle)},
${fields.join("\n")}
}

export default ${name}
`
  )
  files.push(`${OUT}/${name}.ts`)
  fioriNames.push({ name, files })
}

// --- TNT set (V5 for Morning/Evening Horizon, V5/HC for the high-contrast themes) --------------
const tntDir = join(dist, "illustrations-v5/tnt")
const tntHcDir = join(tntDir, "hc")
for (const file of readdirSync(tntDir).filter((f) => /^[A-Z]\w*\.js$/.test(f)).sort()) {
  const name = file.replace(/\.js$/, "")
  const entry = readEntry(join(tntDir, file))
  const hcEntry = existsSync(join(tntHcDir, file)) ? readEntry(join(tntHcDir, file)) : entry
  const hcDir = existsSync(join(tntHcDir, file)) ? tntHcDir : tntDir
  const files = []
  const imports = []
  const fields = []
  const hcFields = []
  for (const size of SIZES) {
    const mod = `${name}-${Cap(size)}`
    const normal = readSvg(join(tntDir, `${entry.sizes[size]}.js`))
    const hc = readSvg(join(hcDir, `${hcEntry.sizes[size]}.js`))
    writeFileSync(
      join(OUT, "tnt", `${mod}.ts`),
      `${HEADER(`SAP TNT illustration "${name}" (${Cap(size)}, V5 and V5/HC)`)}\nexport default ${JSON.stringify(normal)}\nexport const hc = ${JSON.stringify(hc)}\n`
    )
    imports.push(`import ${size}Svg, { hc as ${size}Hc } from "./${mod}"`)
    fields.push(`  ${size}: ${size}Svg,`)
    hcFields.push(`${size}: ${size}Hc`)
    files.push(`${OUT}/tnt/${mod}.ts`)
  }
  writeFileSync(
    join(OUT, "tnt", `${name}.ts`),
    `${HEADER(`SAP TNT illustration "${name}"`)}
import type { IllustrationData } from "../types"
${imports.join("\n")}

const Tnt${name}: IllustrationData = {
  name: ${JSON.stringify(`Tnt${name}`)},
  set: "tnt",
${fields.join("\n")}
  hc: { ${hcFields.join(", ")} },
}

export default Tnt${name}
`
  )
  files.push(`${OUT}/tnt/${name}.ts`)
  tntNames.push({ name, files })
}

writeFileSync(
  join(OUT, "index.ts"),
  `${HEADER("Names of the SAP illustrations")}
// Import illustrations one by one ("@/lib/fiori-illustrations/NoData", "@/lib/fiori-illustrations/tnt/Success")
// so bundles only carry what they use. These lists are for pickers and docs.
export const fioriIllustrationNames = ${JSON.stringify(fioriNames.map((n) => n.name))} as const
export const tntIllustrationNames = ${JSON.stringify(tntNames.map((n) => n.name))} as const
`
)

// --- Registry items ------------------------------------------------------------------------------
const lib = (path) => ({ path, type: "registry:lib" })
const base = [lib(`${OUT}/types.ts`)]
items.push({
  name: "illustrations-core",
  type: "registry:lib",
  title: "SAP illustrations (common)",
  description: `The common Fiori empty/error/success illustrations in all four sizes: ${CORE.join(", ")}. Others: @fiori/illustration-<name>.`,
  registryDependencies: ["@fiori/fiori-theme"],
  files: [...base, lib(`${OUT}/index.ts`), ...fioriNames.filter((n) => CORE.includes(n.name)).flatMap((n) => n.files.map(lib))],
})
for (const n of fioriNames) {
  items.push({
    name: `illustration-${kebab(n.name)}`,
    type: "registry:lib",
    title: `SAP illustration ${n.name}`,
    description: `Fiori illustration "${n.name}" (Scene, Dialog, Spot, Dot) for IllustratedMessage.`,
    registryDependencies: ["@fiori/fiori-theme"],
    files: [...base, ...n.files.map(lib)],
  })
}
for (const n of tntNames) {
  items.push({
    name: `illustration-tnt-${kebab(n.name)}`,
    type: "registry:lib",
    title: `SAP TNT illustration ${n.name}`,
    description: `TNT illustration "${n.name}" (Scene, Dialog, Spot, Dot; normal and high contrast) for IllustratedMessage.`,
    registryDependencies: ["@fiori/fiori-theme"],
    files: [...base, ...n.files.map(lib)],
  })
}
writeFileSync(join(OUT, "registry-items.json"), JSON.stringify(items, null, 2) + "\n")

const missing = CORE.filter((c) => !fioriNames.some((n) => n.name === c))
if (missing.length) throw new Error(`core illustrations missing: ${missing}`)
console.log(`fiori-illustrations written (${fioriNames.length} fiori + ${tntNames.length} tnt illustrations)`)
