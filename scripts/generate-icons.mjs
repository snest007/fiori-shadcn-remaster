// Generates registry/lib/fiori-icons.ts from @ui5/webcomponents-icons (Horizon / v5 set).
// One named export per icon so bundlers tree-shake everything an app doesn't use.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"

const require = createRequire(import.meta.url)
const pkgDir = dirname(require.resolve("@ui5/webcomponents-icons/package.json"))
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version
const dir = join(pkgDir, "dist/v5")

const reserved = new Set(["delete", "export", "import", "new", "in", "for", "if", "do", "switch", "case", "default", "function", "class", "var", "let", "const", "return", "void", "with", "while", "try", "catch", "finally", "throw", "typeof", "instanceof", "this", "super", "extends", "yield", "await", "enum", "private", "public", "protected", "package", "interface", "implements", "static", "let", "arguments", "eval", "null", "true", "false"])

const toIdent = (name) => {
  let id = name.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
  if (/^[0-9]/.test(id)) id = "_" + id
  if (reserved.has(id)) id += "Icon"
  return id
}

// SAP's own logo is a trademark: Apache-2.0 (section 6) grants no trademark rights, so it is not shipped.
const EXCLUDED = new Set(["sap-logo-shape"])

const icons = []
for (const file of readdirSync(dir).filter((f) => f.endsWith(".js")).sort()) {
  const src = readFileSync(join(dir, file), "utf8")
  const name = src.match(/const name = "([^"]+)"/)?.[1]
  const path = src.match(/const pathData = "([^"]+)"/)?.[1]
  if (!name || !path || EXCLUDED.has(name)) continue
  const viewBox = src.match(/const viewBox = "([^"]+)"/)?.[1] ?? "0 0 16 16"
  const ltr = /const ltr = true/.test(src)
  icons.push({ name, id: toIdent(name), path, viewBox, ltr })
}

const lines = [
  `// GENERATED by scripts/generate-icons.mjs, do not edit.`,
  `// SAP Horizon icons from @ui5/webcomponents-icons@${version} (Apache-2.0, © SAP SE or an SAP affiliate company).`,
  `// Excluded: ${[...EXCLUDED].join(", ")} (SAP trademark).`,
  `// \`ltr: true\` means the icon must NOT be mirrored in right-to-left layouts.`,
  ``,
  `export type FioriIconData = { name: string; path: string; viewBox: string; ltr: boolean }`,
  ``,
]
for (const i of icons) {
  lines.push(`export const ${i.id}: FioriIconData = { name: ${JSON.stringify(i.name)}, path: ${JSON.stringify(i.path)}, viewBox: ${JSON.stringify(i.viewBox)}, ltr: ${i.ltr} }`)
}

mkdirSync("registry/lib", { recursive: true })
writeFileSync("registry/lib/fiori-icons.ts", lines.join("\n") + "\n")

// Name list for the docs icon browser.
writeFileSync("docs/src/icon-names.json", JSON.stringify(icons.map((i) => [i.name, i.id])))
console.log(`fiori-icons.ts written (${icons.length} icons)`)
