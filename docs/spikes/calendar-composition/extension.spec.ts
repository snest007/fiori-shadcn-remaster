import { expect, test } from "@playwright/test"
test("neutral structural replacements preserve the exact default tree", async ({ page }) => {
  await page.goto("/spikes/calendar-composition/index.html?probe=neutral&source=registry")
  await expect(page.locator("html")).toHaveAttribute("data-ready", "true")
  const target = page.locator("#probe-calendar")
  const baseline = await target.ariaSnapshot()
  const pixels = await target.screenshot()
  await page.goto("/spikes/calendar-composition/index.html?probe=neutral&source=prototype")
  await expect(page.locator("html")).toHaveAttribute("data-ready", "true")
  expect(await target.ariaSnapshot()).toBe(baseline)
  expect((await target.screenshot()).equals(pixels)).toBe(true)
})
test("owned props survive hostile hooks and getters; content cannot steal the roving stop", async ({ page }) => {
  const warnings: string[] = []
  page.on("console", m => { if (m.type() === "warning") warnings.push(m.text()) })
  await page.goto("/spikes/calendar-composition/index.html?probe=hostile")
  await expect(page.locator("html")).toHaveAttribute("data-ready", "true")
  const cell = page.locator('#probe-calendar [data-date="20240312"]')
  await expect(cell).toHaveAttribute("role", "gridcell")
  await expect(cell).toHaveAttribute("aria-selected", "true")
  await expect(cell).toHaveAttribute("tabindex", "0")
  await expect(page.locator("#stolen-id")).toHaveCount(0)
  await expect(cell).toHaveClass(/consumer-cell/)
  await expect(cell).toHaveAttribute("style", /outline-color: var\(--sapLinkColor\)/)
  await expect(cell.getByRole("button", { name: "Extra" })).toHaveAttribute("tabindex", "-1")
  await expect(page.locator("html")).toHaveAttribute("data-month-name", "Month March")
  await expect(page.locator("html")).toHaveAttribute("data-grid-role", "grid")
  await expect(page.locator("html")).toHaveAttribute("data-row-role", "row")
  await expect(page.locator("html")).toHaveAttribute("data-week-role", "rowheader")
  const data = JSON.parse(await page.locator("html").getAttribute("data-getter") ?? "{}")
  expect(data).toMatchObject({ role: "gridcell", selected: true, tabIndex: 0, color: "var(--sapTextColor)" })
  expect(data.className).toContain("getter-class")
  expect(await page.locator("html").getAttribute("data-context-keys")).not.toMatch(/activate|navElement|extraDayProps/)
  expect(warnings.some(w => w.includes("ignored owned prop role"))).toBe(true)
  await cell.click()
  await expect(page.getByTestId("probe-events")).toHaveText("1")
  await cell.focus()
  await page.keyboard.press("ArrowRight")
  await expect(page.locator('#probe-calendar [data-date="20240313"]')).toBeFocused()
  await expect(page.getByTestId("probe-events")).toHaveText("2")
  await expect(page.locator('#probe-calendar [role=gridcell][tabindex="0"]')).toHaveCount(1)
})
test("generic item count and partial last row are independent of month/year constants", async ({ page }) => {
  // This probe uses default GridPicker rows, unlike the 16-item consumer replacement.
  await page.goto("/spikes/calendar-composition/index.html?probe=items")
  await expect(page.locator("html")).toHaveAttribute("data-ready", "true")
  const grid = page.locator('#probe-calendar [data-picker="item"]')
  await expect(grid.getByRole("gridcell")).toHaveCount(10)
  await expect(grid.getByRole("row")).toHaveCount(4)
  await grid.locator('[data-key="0"]').focus()
  await page.keyboard.press("ArrowRight")
  await expect(grid.locator('[data-key="2"]')).toBeFocused()
  await page.keyboard.press("Control+End")
  await expect(grid.locator('[data-key="9"]')).toBeFocused()
  await page.keyboard.press("End")
  await expect(grid.locator('[data-key="9"]')).toBeFocused()
  await page.keyboard.press(" ")
  await expect(grid.locator('[data-key="9"]')).toHaveAttribute("aria-selected", "true")
  await expect(grid.locator('[data-key="1"]')).toHaveAttribute("aria-disabled", "true")
})

test("uncontrolled keyed focus recovers when the consumer replaces the item model", async ({ page }) => {
  await page.goto("/spikes/calendar-composition/index.html?probe=items")
  await expect(page.locator("html")).toHaveAttribute("data-ready", "true")
  const grid = page.locator('#probe-calendar [data-picker="item"]')
  await grid.locator('[data-key="0"]').focus()
  await page.keyboard.press("Control+End")
  await expect(grid.locator('[data-key="9"]')).toBeFocused()
  await page.getByRole("button", { name: "Replace items" }).click()
  await expect(grid.locator('[data-key="10"]')).toHaveAttribute("tabindex", "0")
  await expect(grid.locator('[role=gridcell][tabindex="0"]')).toHaveCount(1)
  await grid.locator('[data-key="10"]').focus()
  await page.keyboard.press("ArrowRight")
  await expect(grid.locator('[data-key="12"]')).toBeFocused()
  await expect(page.locator('#probe-calendar [aria-keyshortcuts]:visible')).toHaveCount(0)
})

test("month and year content shorthands receive default content, state and resolved locale", async ({ page }) => {
  await page.goto("/spikes/calendar-composition/index.html?probe=slots")
  await expect(page.locator("html")).toHaveAttribute("data-ready", "true")
  const month = page.getByTestId("probe-month-2")
  await expect(month).toHaveText("March")
  await expect(month).toHaveAttribute("data-locale", "en-US")
  await expect(month).toHaveAttribute("data-focused", "true")
  await expect(month).toHaveAttribute("data-selected", "true")
  await page.locator('#probe-calendar [data-slot="calendar-year-button"]').click()
  const year = page.locator('#probe-calendar [data-focus-ref]').getByTestId("probe-year")
  await expect(year).toHaveText("2024")
  await expect(year).toHaveAttribute("data-locale", "en-US")
  await expect(year).toHaveAttribute("data-focused", "true")
  await expect(year).toHaveAttribute("data-selected", "true")
})
