// Fiscal year variants as an S/4 system would deliver them (I_FiscalYearPeriod-like rows).
// The period boundaries are written out literally — never derived — so the adapter and the tests
// check against data, not against a second copy of the same algorithm.
//
// K4   — calendar year, 12 periods + 4 special periods (SAP standard variant).
// V3   — April to March, 12 periods + 4 special periods; fiscal year = year in which it starts
//        (year shift -1 for January–March, as in SAP V3).
// Z445 — custom 4-4-5 week pattern, Monday start; FY2026 has 53 weeks (P12 has 6 weeks).

export type PeriodRow = readonly [fiscalYear: number, period: number, start: string, end: string]

export type FiscalVariant = {
  id: string
  /** Shown in the variant switch. */
  name: string
  /** Number of regular (posting-date-derived) periods. */
  regularPeriods: number
  /** Special periods 13…16 subdivide the last regular period; they are chosen, never derived from a date. */
  specialPeriods: number
  /** Regular period table, ascending and gap-free. */
  rows: readonly PeriodRow[]
  /** Week-based variants have fiscal weeks that differ from calendar weeks. */
  weekBased: boolean
}

